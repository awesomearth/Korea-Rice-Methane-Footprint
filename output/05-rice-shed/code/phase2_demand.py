"""Phase 2 (P2) - rice demand by consuming unit (si/gun/gu), analysis year 2025.

Inputs : data/raw/pop/mois_bjd_pop_20251231.csv, data/raw/kosis/DT_1ED0001.csv
Outputs: data/processed/demand.csv, 02-demand.md
Run from output/05-rice-shed/:  python code/phase2_demand.py
"""
import os

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
YEAR = "2025"


def per_capita_rice_kg():
    """KOSIS DT_1ED0001: 곡류 '10 쌀', 용도 '00 계', item T10 전가구, YEAR."""
    raw = pd.read_csv(os.path.join(ROOT, "data/raw/kosis/DT_1ED0001.csv"), encoding="utf-8-sig",
                      header=None, dtype=str)
    years, items = raw.iloc[0], raw.iloc[1]
    col = [i for i in range(2, raw.shape[1])
           if years[i].startswith(f"Y{YEAR}") and items[i].startswith("T10")]
    assert len(col) == 1, col
    row = raw[(raw[0] == "10 쌀") & (raw[1] == "00 계")]
    assert len(row) == 1
    return float(row.iloc[0, col[0]])


def main():
    pc = per_capita_rice_kg()
    pop = pd.read_csv(os.path.join(ROOT, "data/raw/pop/mois_bjd_pop_20251231.csv"), encoding="cp949", dtype=str)
    assert pop["기준연월"].nunique() == 1
    pop["population"] = pd.to_numeric(pop["계"].str.replace(",", ""), errors="raise")
    pop["admin_code"] = pop["법정동코드"].str[:5]
    g = pop.groupby("admin_code").agg(sido=("시도명", "first"), sgg=("시군구명", "first"),
                                      population=("population", "sum")).reset_index()
    g["name"] = np.where(g["sgg"].fillna("").str.strip() == "", g["sido"], g["sido"] + " " + g["sgg"].fillna(""))
    assert g["population"].notna().all() and (g["population"] > 0).all()

    nat_pop = int(g["population"].sum())
    control_t = nat_pop * pc / 1000.0  # national household rice demand, t milled rice
    raw_t = g["population"] * pc / 1000.0  # bottom-up demand
    g["share_national"] = raw_t / raw_t.sum()
    g["rice_demand_t"] = g["share_national"] * control_t
    resid_before = raw_t.sum() - control_t
    resid_after = g["rice_demand_t"].sum() - control_t
    share_err = g["share_national"].sum() - 1.0
    out = g[["admin_code", "name", "population", "rice_demand_t", "share_national"]]
    os.makedirs(os.path.join(ROOT, "data/processed"), exist_ok=True)
    out.to_csv(os.path.join(ROOT, "data/processed/demand.csv"), index=False, encoding="utf-8")

    ok = abs(share_err) <= 1e-9 and out["population"].notna().all()
    s = out.sort_values("rice_demand_t", ascending=False)
    fmt = lambda d: "\n".join(f"| {r.admin_code} | {r.name} | {r.population:,} | {r.rice_demand_t:,.1f} | {r.share_national:.5f} |"
                              for r in d.itertuples())
    hdr = "| admin_code | name | population | rice_demand_t | share_national |\n|---|---|---|---|---|"
    md = f"""# 02 — Demand Side (Idea 2, Phase 2 / P2)

Generated by `code/phase2_demand.py` from `data/raw/pop/mois_bjd_pop_20251231.csv` and `data/raw/kosis/DT_1ED0001.csv`. Output: `data/processed/demand.csv`.

## Method
1. **Aggregate population.** The 2025-12-31 법정동 resident counts (column `계`) are summed to the consuming unit: the first 5 digits of the 법정동코드 (`00-scope.md` (b)).
2. **Bottom-up demand.** Each unit's population is multiplied by the national per capita household rice consumption. The rate comes from DT_1ED0001: 곡류 "10 쌀", 용도 "00 계", item "T10 전가구", {YEAR}.
3. **Rescale to the control total.** Only each unit's share of the bottom-up national demand is kept. Shares are then rescaled to the national control total, defined as national population × per capita consumption. This follows `01-method-summary.md` Step A.4.
   - A single national per capita rate is the only consumption input Idea 2 has. It makes every unit's share equal to its population share, so the rescaling step is an identity here; it is kept so that a later demographic or regional profile could be substituted without changing the pipeline.

## Results
| Quantity | Value |
|---|---|
| Consuming units | {len(out)} |
| Units with null or zero population | {int((out['population'].isna() | (out['population'] <= 0)).sum())} |
| National population (2025-12-31) | {nat_pop:,} |
| Per capita household rice consumption, {YEAR} | {pc} kg milled rice / person / yr |
| **National control total (household rice demand)** | **{control_t:,.1f} t** ({control_t/1e6:.4f} Mt) |
| Residual of the bottom-up sum vs control, before rescaling | {resid_before:.3e} t |
| Residual after rescaling (Σ rice_demand_t − control) | {resid_after:.3e} t |
| Σ share_national − 1 | {share_err:.3e} |
| Done criterion (share sums to 1 ± 1e-9; no null population) | **{'MET' if ok else 'NOT MET'}** |

### Top 10 units by rice demand
{hdr}
{fmt(s.head(10))}

### Bottom 10 units by rice demand
{hdr}
{fmt(s.tail(10).iloc[::-1])}

## Notes
- **Household consumption only.** The control total covers household consumption. Non-household uses (processing, food service, stocks) are outside the demand vector; Phase 4 handles them as the explicit slack node fixed in `00-scope.md` (b).
- **Demand is proportional to population.** Because one national per capita rate is applied, per capita demand is identical in every unit ({pc} kg). Per capita footprints can then differ only through sourcing (Phase 5), as in the paper's finding that consumption is a poor proxy (`01-method-summary.md` §1).
"""
    open(os.path.join(ROOT, "02-demand.md"), "w", encoding="utf-8").write(md)
    print(f"units={len(out)} pop={nat_pop} pc={pc} control_t={control_t:.3f} share_err={share_err:.2e} ok={ok}")


if __name__ == "__main__":
    main()
