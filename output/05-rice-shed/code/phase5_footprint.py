"""Phase 5 - city rice-shed CH4 footprints, 2025.

Inputs : data/processed/flows.csv, data/processed/supply_intensity.csv, data/processed/demand.csv
Outputs: data/processed/footprint.csv, 05-footprint.md
Run from output/05-rice-shed/:  python code/phase5_footprint.py
"""
import json
import os

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = lambda *a: os.path.join(ROOT, *a)


def footprints(flows, s, d):
    """Footprint per consuming unit = sum over sources of flow (t) x source kgCO2e/kg (= tCO2e/t)."""
    f = flows.merge(s[["admin_code", "kgco2e_per_kg"]], left_on="from_code", right_on="admin_code")
    f["tco2e"] = f.tonnes * f.kgco2e_per_kg
    cons = f[f.to_code != "SLACK"].groupby("to_code").agg(
        footprint_tco2e=("tco2e", "sum"), received_t=("tonnes", "sum"),
        n_sources=("from_code", "nunique"),
        tkm=("km", lambda k: float((k * f.loc[k.index, "tonnes"]).sum())))
    slack = float(f.loc[f.to_code == "SLACK", "tco2e"].sum())
    out = d.merge(cons, left_on="admin_code", right_index=True, how="left")
    return out, slack, f


def main():
    flows = pd.read_csv(R("data/processed/flows.csv"), dtype={"from_code": str, "to_code": str})
    s = pd.read_csv(R("data/processed/supply_intensity.csv"), dtype={"admin_code": str})
    d = pd.read_csv(R("data/processed/demand.csv"), dtype={"admin_code": str})
    fac = json.load(open(R("data/processed/ch4_factors.json")))
    out, slack_tco2e, _ = footprints(flows, s, d)
    nat_int = float((s.ch4_t.sum() * fac["gwp"]) / s.production_t.sum())  # kgCO2e/kg, Phase 3 national average
    out["per_capita_kgco2e"] = out.footprint_tco2e * 1000 / out.population
    out["per_capita_consumption_kg"] = out.rice_demand_t * 1000 / out.population
    out["sourcing_intensity_kgco2e_per_kg"] = out.footprint_tco2e / out.rice_demand_t
    out["footprint_natavg_tco2e"] = out.rice_demand_t * nat_int
    out["ratio_spatial_to_natavg"] = out.footprint_tco2e / out.footprint_natavg_tco2e
    out["mean_sourcing_km"] = out.tkm / out.received_t
    cols = ["admin_code", "name", "population", "rice_demand_t", "footprint_tco2e", "per_capita_kgco2e",
            "per_capita_consumption_kg", "sourcing_intensity_kgco2e_per_kg", "footprint_natavg_tco2e",
            "ratio_spatial_to_natavg", "n_sources", "mean_sourcing_km"]
    out[cols].to_csv(R("data/processed/footprint.csv"), index=False, encoding="utf-8")

    cons_kt = out.footprint_tco2e.sum() / 1000
    nat_kt = fac["national_kt_co2e"]
    tot_kt = cons_kt + slack_tco2e / 1000
    rel = (tot_kt - nat_kt) / nat_kt
    pc = out.per_capita_kgco2e
    var_cons = float(out.per_capita_consumption_kg.var())
    r_cons = float(np.corrcoef(pc, out.per_capita_consumption_kg)[0, 1]) if var_cons > 0 else float("nan")
    r_int = float(np.corrcoef(pc, out.sourcing_intensity_kgco2e_per_kg)[0, 1])
    rr = out.ratio_spatial_to_natavg
    natavg_pc = float(out.footprint_natavg_tco2e.sum() * 1000 / out.population.sum())
    hi = out.sort_values("per_capita_kgco2e", ascending=False)
    row = lambda r: (f"| {r.admin_code} | {r.name} | {r.population:,} | {r.footprint_tco2e:,.0f} | {r.per_capita_kgco2e:.1f} | "
                     f"{r.sourcing_intensity_kgco2e_per_kg:.3f} | {r.ratio_spatial_to_natavg:.3f} | {r.mean_sourcing_km:.0f} |")
    th = ("| admin_code | Unit | Population | Footprint (t CO2e) | Per capita (kg CO2e) | Sourcing intensity (kg CO2e/kg) | "
          "Ratio to national avg | Mean sourcing km |\n|---|---|---|---|---|---|---|---|")
    done = abs(rel) <= 0.001
    md = f"""# 05 — City Footprints (Idea 2, Phase 5)

Generated by `code/phase5_footprint.py` from `data/processed/flows.csv`, `supply_intensity.csv` and `demand.csv`. Output: `data/processed/footprint.csv`.

## Method
- **Footprint.** footprint_j = Σ_i flow_ij (t) × kgCO2e/kg_i, where i is the producing unit (`supply_intensity.csv`) and j the consuming unit (`01-method-summary.md` Step E.10).
- **Per capita footprint** = footprint_j / population_j.
- **Sourcing-weighted intensity** = footprint_j / demand_j.
- **National-average counterfactual** = demand_j × {nat_int:.4f} kg CO2e/kg. This is Phase 3's national average intensity: national CH4 × 28 / national production.
- **Ratio** = spatial ÷ national-average footprint.

## Results
| Quantity | Value |
|---|---|
| **Total household rice-shed footprint (Σ 252 consuming units)** | **{cons_kt:,.1f} kt CO2e** |
| Footprint embodied in the slack node (non-household disposition) | {slack_tco2e/1000:,.1f} kt CO2e ({slack_tco2e/1000/nat_kt:.1%} of national paddy CH4) |
| Σ consuming units + slack | {tot_kt:,.1f} kt CO2e |
| National paddy CH4, Phase 3 (`ch4_factors.json`) | {nat_kt:,.1f} kt CO2e |
| Relative difference | {rel:+.2e} |
| Per capita footprint, mean ± sd over units (unweighted) | **{pc.mean():.1f} ± {pc.std():.1f} kg CO2e / person / yr** |
| Per capita footprint, population-weighted national value | {out.footprint_tco2e.sum()*1000/out.population.sum():.1f} kg CO2e |
| Per capita footprint under national-average intensity (identical for all units) | {natavg_pc:.1f} kg CO2e |
| Per capita range (min – max) | {pc.min():.1f} – {pc.max():.1f} kg CO2e (max/min {pc.max()/pc.min():.2f}) |
| **Ratio spatial / national-average, range** | **{rr.min():.3f} – {rr.max():.3f}** (median {rr.median():.3f}; {int((rr < 1).sum())} units below 1, {int((rr > 1).sum())} above) |
| **r (per capita footprint, per capita consumption)** | **undefined** (per capita consumption has variance {var_cons:.1e}: one national rate of {out.per_capita_consumption_kg.iloc[0]:.1f} kg applies to every unit) |
| **r (per capita footprint, sourcing-weighted intensity)** | **{r_int:.4f}** |

**Reading the correlations.** Idea 2 has one national per capita consumption rate (DT_1ED0001), so per capita consumption does not vary across units and its Pearson correlation with anything is mathematically undefined (0/0). For the same reason, per capita footprint = 53.9 kg × sourcing intensity, and its correlation with sourcing intensity is 1 by construction. The paper's two coefficients (r = −0.04 and 0.99; `01-method-summary.md` §1) cannot be tested independently with these inputs. All between-unit variation here comes from **where** rice is sourced.

**Below the national average.** The household footprint ({cons_kt:,.0f} kt) is lower than demand × national average ({out.footprint_natavg_tco2e.sum()/1000:,.0f} kt) because the cost-minimizing LP assigns the slack to remote, low-yield, high-intensity producers in the southwest (`04-flows.md`, slack table). Households are then supplied mostly from closer, higher-yield units. The ratio range should be read with that mechanism in mind.

### Highest 10 per capita footprints
{th}
{chr(10).join(row(r) for r in hi.head(10).itertuples())}

### Lowest 10 per capita footprints
{th}
{chr(10).join(row(r) for r in hi.tail(10).iloc[::-1].itertuples())}

## Done criterion
- Σ footprint over units (plus the explicitly named slack node) equals the Phase 3 national CH4 total within 0.1%: **{'MET' if done else 'NOT MET'}** ({rel:+.2e}).
  - **Caveat:** the 252 consuming units alone account for {cons_kt/nat_kt:.1%} of national paddy CH4. The remainder is embodied in non-household disposition.
- Both correlation coefficients reported: **MET**. One is undefined, for the reason stated above; the other is 1 by construction.
"""
    open(R("05-footprint.md"), "w", encoding="utf-8").write(md)
    print(f"cons_kt={cons_kt:.1f} slack_kt={slack_tco2e/1000:.1f} tot={tot_kt:.1f} nat={nat_kt:.1f} rel={rel:.2e} "
          f"pc={pc.mean():.2f}±{pc.std():.2f} ratio={rr.min():.3f}-{rr.max():.3f} r_int={r_int:.4f} done={done}")


if __name__ == "__main__":
    main()
